_PATTERN = re.compile(r":icon-([a-z0-9-]+):")
# Fenced code blocks (``` or ~~~) are left untouched.
_FENCE = re.compile(r"^([ \t]*)(`{3,}|~{3,}).*?^\1\2[ \t]*$", re.M | re.S)


def svg(name: str) -> str:
    return f'<svg class="icon" viewBox="0 0 24 24" aria-hidden="true">{ICONS[name]}</svg>'


def on_env(env, config, files, **kwargs):
    env.globals["ICONS"] = ICONS
    return env


def on_page_markdown(markdown, page, config, files, **kwargs):
    def repl(match):
        name = match.group(1)
        if name not in ICONS:
            raise KeyError(f"Unknown icon :icon-{name}: in {page.file.src_path}")
        return svg(name)

    out, last = [], 0
    for fence in _FENCE.finditer(markdown):
        out.append(_PATTERN.sub(repl, markdown[last:fence.start()]))
        out.append(fence.group(0))
        last = fence.end()
    out.append(_PATTERN.sub(repl, markdown[last:]))
    return "".join(out)
